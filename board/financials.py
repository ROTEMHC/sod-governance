def ratios(year: int) -> dict:
    d = {k: val[year] for k, val in DATA.items()}
    return {
        "gross_margin": d["gross_profit"] / d["sales"],
        "operating_margin": d["operating_profit"] / d["sales"],
        "net_margin": d["net_profit"] / d["sales"],
        "current_ratio": d["current_assets"] / d["current_liabilities"],
        "quick_ratio": (d["current_assets"] - d["inventory"]) / d["current_liabilities"],
        "equity_ratio": d["equity"] / d["total_assets"],
        "cfo_to_net": d["cfo"] / d["net_profit"],
    }


