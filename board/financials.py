    for k in keys:
        note = NOTES.get(k)
        rows.append({
            "item": LABELS[k],
            "y25": f"{DATA[k][2025]:,.1f}",
            "p25": f"{DATA[k][2025] / DATA[base][2025]:.2%}",
            "y24": f"{DATA[k][2024]:,.1f}",
            "p24": f"{DATA[k][2024] / DATA[base][2024]:.2%}",
            "chg": f"{growth(k):+.2%}",
            "note": {"text": note[0], "tip": note[1]} if note else "",
        })
    return rows


